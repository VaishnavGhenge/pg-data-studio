// Regenerates src/main/rdsCaBundle.ts from Amazon's public RDS trust store.
// These are Amazon's root CA certificates (public keys only), the same file
// AWS publishes for every RDS client. Run when AWS adds or rotates a CA:
//   node scripts/update-rds-ca.mjs
import { writeFileSync } from "node:fs";
import { X509Certificate } from "node:crypto";

const SOURCE = "https://truststore.pki.rds.amazonaws.com/global/global-bundle.pem";
const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`Download failed: ${res.status} ${res.statusText}`);
const pem = (await res.text()).replace(/\r\n/g, "\n").trim();
const certs = pem.match(/-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----/g) ?? [];
if (certs.length < 10)
  throw new Error(`Expected the full RDS bundle, got ${certs.length} certificates`);
for (const cert of certs) {
  const x = new X509Certificate(cert);
  if (!/Amazon/.test(x.issuer)) throw new Error("Unexpected issuer: " + x.issuer);
}
const today = new Date().toISOString().slice(0, 10);
writeFileSync(
  new URL("../src/main/rdsCaBundle.ts", import.meta.url),
  `// Generated by scripts/update-rds-ca.mjs on ${today}. Do not edit by hand.
// Amazon RDS root CA certificates (${certs.length}), public, from
// ${SOURCE}
export const RDS_CA_BUNDLE = \`${certs.join("\n")}\n\`;
`,
);
console.log(`Wrote ${certs.length} certificates`);
